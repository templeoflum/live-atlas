// Builds the public GitHub Pages copy in ../site: only what the page loads.
// Never copies the manual cache, tests, docs, snapshots or unused media.
// Usage: node build-pages.mjs   (then commit and push ../site)
import {readFile,writeFile,mkdir,copyFile,stat} from 'node:fs/promises';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const here=new URL('./',import.meta.url),out=new URL('../site/',import.meta.url);
const html=await readFile(new URL('index.html',here),'utf8');
const scripts=[...html.matchAll(/<script src="([^"]+)"/g)].map(m=>m[1]);
if(scripts.some(s=>/^(https?:)?\/\//.test(s)))throw Error('Unexpected external script');
const model=require('./atlas-model.cjs')();
const images=[...new Set(Object.values(model.captures).filter(c=>c.file&&!c.error).map(c=>'assets/'+c.file))];
const files=['index.html','atlas.css',...scripts,...images];
let bytes=0;
for(const name of files){
  const dest=new URL(name,out);await mkdir(new URL('./',dest),{recursive:true});
  await copyFile(new URL(name,here),dest);bytes+=(await stat(dest)).size;
}
await writeFile(new URL('.nojekyll',out),'');
await writeFile(new URL('README.md',out),`# Ableton Live, Mapped\n\nA personal study atlas of Ableton Live 12. Open it at the GitHub Pages address for this repository.\n\nManual illustrations and captions: © Ableton AG, from the [Live 12 manual](https://www.ableton.com/en/live-manual/12/welcome-to-live/). History images are credited on each figure. Independent atlas; not an Ableton publication.\n\nFlags and the session trace are saved in each visitor's own browser (localStorage); nothing is sent anywhere.\n\nThis folder is generated by \`build-pages.mjs\` in the working project. Edit there, rebuild, then commit.\n`);
console.log(JSON.stringify({scripts:scripts.length,images:images.length,files:files.length+2,megabytes:+(bytes/1e6).toFixed(1)}));

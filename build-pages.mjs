// Builds the public GitHub Pages copy in ../site: only what the page loads.
// Never copies the manual cache, tests, docs, snapshots or unused media.
// Public by default (policy of 14 Oct 2026: never publish third-party material,
// link to it instead): no manual figures or history images are copied, and the
// page renders each figure as a link to its manual page or source. The local
// atlas (serve.mjs) is unchanged and still shows the images.
// Usage: node build-pages.mjs [--out DIR] [--with-images]   (then commit ../site)
//   --with-images  the earlier build that hosts every figure; not for publishing.
import {readFile,writeFile,mkdir,copyFile,stat,rm} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {pathToFileURL} from 'node:url';
const require=createRequire(import.meta.url);
const args=process.argv.slice(2),flag=name=>args.includes(name);
const outArg=args[args.indexOf('--out')+1];
const here=new URL('./',import.meta.url);
const out=flag('--out')?pathToFileURL(outArg.replace(/\/?$/,'/')):new URL('../site/',import.meta.url);
if(out.href===here.href)throw Error('Refusing to build into the source folder');
const hostImages=flag('--with-images');
let html=await readFile(new URL('index.html',here),'utf8');
const scripts=[...html.matchAll(/<script src="([^"]+)"/g)].map(m=>m[1]);
if(scripts.some(s=>/^(https?:)?\/\//.test(s)))throw Error('Unexpected external script');
const model=require('./atlas-model.cjs')();
const images=hostImages?[...new Set(Object.values(model.captures).filter(c=>c.file&&!c.error).map(c=>'assets/'+c.file))]:[];
const files=['atlas.css',...scripts,...images];
let bytes=0;
if(!hostImages){
  // Earlier builds copied the figures here; a public build must not leave them behind.
  await rm(new URL('assets/',out),{recursive:true,force:true});
  html=html.replace(`<script src="${scripts[0]}"`,`<script src="public-build.js" defer></script>\n  <script src="${scripts[0]}"`);
  await mkdir(out,{recursive:true});
  await writeFile(new URL('public-build.js',out),'// Written by build-pages.mjs: figures render as links to their sources, not hosted images.\nconst publicBuild=true;\n');
}
await mkdir(out,{recursive:true});
await writeFile(new URL('index.html',out),html);
for(const name of files){
  const dest=new URL(name,out);await mkdir(new URL('./',dest),{recursive:true});
  await copyFile(new URL(name,here),dest);bytes+=(await stat(dest)).size;
}
await writeFile(new URL('.nojekyll',out),'');
const credits=hostImages
  ?`Manual illustrations and captions: © Ableton AG, from the [Live 12 manual](https://www.ableton.com/en/live-manual/12/welcome-to-live/). History images are credited on each figure.`
  :`This site hosts no third-party images. Each Live 12 manual figure is a link to its page in the [Live 12 manual](https://www.ableton.com/en/live-manual/12/welcome-to-live/) (© Ableton AG), and each history image is a link to where its owner publishes it, with their credit.`;
await writeFile(new URL('README.md',out),`# Ableton Live, Mapped\n\nA personal study atlas of Ableton Live 12. Open it at the GitHub Pages address for this repository.\n\n${credits} Independent atlas; not an Ableton publication.\n\nFlags and the session trace are saved in each visitor's own browser (localStorage); nothing is sent anywhere.\n\nThis folder is generated by \`build-pages.mjs\` in the working project. Edit there, rebuild, then commit.\n`);
console.log(JSON.stringify({mode:hostImages?'with-images':'public',scripts:scripts.length,images:images.length,files:files.length+3+(hostImages?0:1),megabytes:+(bytes/1e6).toFixed(1)}));
